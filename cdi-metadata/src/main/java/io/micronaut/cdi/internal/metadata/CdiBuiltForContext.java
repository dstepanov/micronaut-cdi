package io.micronaut.cdi.internal.metadata;

import io.micronaut.core.annotation.Internal;

import java.lang.annotation.Documented;
import java.lang.annotation.ElementType;
import java.lang.annotation.Retention;
import java.lang.annotation.RetentionPolicy;
import java.lang.annotation.Target;

/**
 * Marks a runtime definition the container built for the one context it registered it with - a synthetic bean, the
 * bean of a portable extension, the scope of a context an extension registered - rather than one a program built and
 * may register with more than one context. What the container works out of such a definition through its context,
 * the bean types, is kept on it.
 *
 * @author Denis Stepanov
 * @since 1.0
 */
@Documented
@Retention(RetentionPolicy.RUNTIME)
@Target(ElementType.TYPE)
@Internal
public @interface CdiBuiltForContext {
}
