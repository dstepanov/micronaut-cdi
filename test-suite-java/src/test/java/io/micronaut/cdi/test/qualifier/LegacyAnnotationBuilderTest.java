package io.micronaut.cdi.test.qualifier;

import io.micronaut.context.ApplicationContext;
import io.micronaut.core.annotation.AnnotationBuilder;
import io.micronaut.core.convert.ConversionService;
import jakarta.enterprise.context.Dependent;
import jakarta.enterprise.inject.Any;
import jakarta.enterprise.inject.Instance;
import jakarta.enterprise.inject.spi.CDI;
import jakarta.enterprise.util.AnnotationLiteral;
import jakarta.inject.Qualifier;
import org.junit.jupiter.api.Test;

import java.lang.annotation.Retention;
import java.lang.annotation.RetentionPolicy;
import java.util.Map;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * A builder generated by a version of Micronaut that cannot read an annotation answers its reader with an
 * {@code UnsupportedOperationException}, which is told from nothing else by its stack trace - a JVM may omit that.
 * The literal is read by the reflection module where it is there, whatever the trace says.
 */
class LegacyAnnotationBuilderTest {

    @Qualifier
    @Retention(RetentionPolicy.RUNTIME)
    @interface Flag {
        String value();

        final class Literal extends AnnotationLiteral<Flag> implements Flag {

            private final String value;

            Literal(String value) {
                this.value = value;
            }

            @Override
            public String value() {
                return value;
            }
        }
    }

    /**
     * Registered for {@link Flag} (META-INF/micronaut under the test resources), as the builder of an earlier version
     * of Micronaut: it builds, and reads nothing, here with the stack trace a JVM may leave out left out.
     */
    @SuppressWarnings("checkstyle:TypeName")
    public static final class io_micronaut_cdi_test_qualifier_LegacyAnnotationBuilderTest_Flag$AnnotationBuilder
        implements AnnotationBuilder<Flag> {

        @Override
        public Class<Flag> annotationType() {
            return Flag.class;
        }

        @Override
        public Flag build(Map<? extends CharSequence, ?> values, ConversionService conversionService) {
            Object value = values.get("value");
            return new Flag.Literal(value == null ? "" : value.toString());
        }

        @Override
        public Map<String, Object> toMap(Flag annotation) {
            UnsupportedOperationException unsupported = new UnsupportedOperationException("cannot read");
            unsupported.setStackTrace(new StackTraceElement[0]);
            throw unsupported;
        }
    }

    interface Lamp {
    }

    @Flag("red")
    @Dependent
    static class RedLamp implements Lamp {
    }

    @Test
    void aLiteralTheLegacyBuilderCannotReadIsReadReflectively() {
        try (ApplicationContext ignored = ApplicationContext.run()) {
            assertTrue(AnnotationBuilder.find(Flag.class).isPresent(), "the legacy builder is registered");
            Instance<Lamp> lamps = CDI.current().select(Lamp.class, Any.Literal.INSTANCE);
            assertEquals(RedLamp.class, lamps.select(new Flag.Literal("red")).get().getClass());
            assertTrue(lamps.select(new Flag.Literal("blue")).isUnsatisfied());
        }
    }
}
